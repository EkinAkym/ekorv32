`include "ekorv32_defines.vh"

//----------------------------------------------------------------------//
//================ MODULE PARAMETERS,INPUTS AND OUTPUTS ================//
//----------------------------------------------------------------------//
module ekorv32_core_pc_unit (
    input clk_i,
    input rst_i,
    input [`PC_OP_LENM:`PC_OP_LENL] pc_op_i,
    input [`RVLENM1:`RVLEN0] branch_pc_i,
    output [`RVLENM1:`RVLEN0] pc_o
);
//----------------------------------------------------------------------//
//============================ LOCALPARAMS =============================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//============================= REGISTERS ==============================//
//----------------------------------------------------------------------//
    reg [`RVLENM1:`RVLEN0] pc_reg;
//----------------------------------------------------------------------//
//=============================== WIRES ================================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//=========================== STATE MACHINE ============================//
//----------------------------------------------------------------------//
  
//----------------------------------------------------------------------//
//=========================== INSTANTIATIONS ===========================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//============================== PROCESS ===============================//
//----------------------------------------------------------------------//
    always @(posedge clk_i or posedge rst_i) begin
        if(rst_i) begin
            pc_reg <= `ADDR_RESET;
        end else begin
            case (pc_op_i)
            `PC_OP_RESET: begin
                pc_reg <= `ADDR_RESET;
            end
            `PC_OP_INC: begin
                pc_reg <= pc_reg + `PC_ADD;
            end
            `PC_OP_ASSIGN: begin
                pc_reg <= branch_pc_i;
            end
            `PC_OP_NO_OP: begin
            end
            endcase
        end
    end
//----------------------------------------------------------------------//
//============================== ASSIGNS ===============================//
//----------------------------------------------------------------------//
    assign pc_o = pc_reg;

endmodule
