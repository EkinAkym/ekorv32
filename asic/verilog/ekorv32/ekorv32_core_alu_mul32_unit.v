`include "ekorv32_defines.vh"

//----------------------------------------------------------------------//
//================ MODULE PARAMETERS,INPUTS AND OUTPUTS ================//
//----------------------------------------------------------------------//
module ekorv32_core_alu_mul32_unit (
    input  clk_i,
    input  rst_i,
    input  en_i,
    input  [`RVLENM1:`RVLEN0] mul1_i,
    input  [`RVLENM1:`RVLEN0] mul2_i,
    output [`RVLEN2M1:`RVLEN0] sres_o,
    output [`RVLEN2M1:`RVLEN0] ures_o,
    output done_o
);
//----------------------------------------------------------------------//
//============================ LOCALPARAMS =============================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//============================= REGISTERS ==============================//
//----------------------------------------------------------------------//
    reg [`A5:`A0] cnt_reg;
    reg [`RVLEN2M1:`RVLEN0] smuld_reg;
    reg [`RVLEN2M1:`RVLEN0] saccum_reg;
    reg [`RVLENM1:`RVLEN0] smulr_reg;
    reg [`RVLEN2M1:`RVLEN0] umuld_reg;
    reg [`RVLEN2M1:`RVLEN0] uaccum_reg;
    reg [`RVLENM1:`RVLEN0] umulr_reg;
    reg busy_reg;
    reg [`RVLEN2M1:`RVLEN0] sres_reg;
    reg [`RVLEN2M1:`RVLEN0] ures_reg; 
    reg done_reg; 
//----------------------------------------------------------------------//
//=============================== WIRES ================================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//=========================== STATE MACHINE ============================//
//----------------------------------------------------------------------//
  
//----------------------------------------------------------------------//
//=========================== INSTANTIATIONS ===========================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//============================== PROCESS ===============================//
//----------------------------------------------------------------------//
 always @(posedge clk_i or posedge rst_i) begin
    if(rst_i) begin
        cnt_reg <= `A0;
        smuld_reg <= `A0;
        saccum_reg <= `A0;
        smulr_reg <= `A0;
        umuld_reg <= `A0;
        uaccum_reg <= `A0;
        umulr_reg <= `A0;
        busy_reg <= `A0;
        sres_reg <= `A0;
        ures_reg <= `A0;
        done_reg <= `A0;
    end else begin
        if (en_i && !busy_reg) begin
            smuld_reg  <= {{`A32{mul1_i[`A31]}}, mul1_i}; // sign-extend
            smulr_reg <= mul2_i;
            saccum_reg <= `A0;
            umuld_reg <= {`RV32B0, mul1_i}; // zero-extend
            umulr_reg <= mul2_i;
            uaccum_reg <= `A0;
            cnt_reg <= `A0;
            busy_reg <= `RV1B1;
            done_reg <= `RV1B0;
        end else if (busy_reg) begin
            if(smulr_reg[`A0]) 
                saccum_reg <= saccum_reg + smuld_reg;
                smuld_reg <= smuld_reg << `A1;
                smulr_reg <= smulr_reg >> `A1; 
            if(umulr_reg[`A0])
                uaccum_reg <= uaccum_reg + umuld_reg;
                umuld_reg <= umuld_reg << `A1;
                umulr_reg <= umulr_reg >> `A1;
                cnt_reg <= cnt_reg + `A1;   
            if (cnt_reg == `A31) begin
                sres_reg <= saccum_reg;
                ures_reg <= uaccum_reg;
                done_reg <= `RV1B1;
                busy_reg <= `RV1B0;
            end
        end else begin
            done_reg <= `RV1B0;
        end
    end
 end
//----------------------------------------------------------------------//
//============================== ASSIGNS ===============================//
//----------------------------------------------------------------------//
    assign ures_o = ures_reg;
    assign sres_o = sres_reg;
    assign done_o = done_reg;
endmodule
