//----------------------------------------------------------------------//
//============================== INCLUDES ==============================//
//----------------------------------------------------------------------//
`include "ekorv32_defines.vh"

//----------------------------------------------------------------------//
//================ MODULE PARAMETERS,INPUTS AND OUTPUTS ================//
//----------------------------------------------------------------------//
module ekorv32_core_register_unit (
    input clk_i,
    input rst_i,
    input en_i,
    input [`RVLENM1:`RVLEN0] data_i,
    input [`SELECTION:`RVLEN0] sel_rs1_i,
    input [`SELECTION:`RVLEN0] sel_rs2_i,
    input [`SELECTION:`RVLEN0] sel_rd_i,
    input we_i,
    output [`RVLENM1:`RVLEN0] data_rs1_o,
    output [`RVLENM1:`RVLEN0] data_rs2_o
);
//----------------------------------------------------------------------//
//============================ LOCALPARAMS =============================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//============================= REGISTERS ==============================//
//----------------------------------------------------------------------//
    reg [`RVLENM1:`RVLEN0] memRS1 [`RVLEN0:`RVLENM1];
    reg [`RVLENM1:`RVLEN0] memRS2 [`RVLEN0:`RVLENM1];
    reg [`RVLENM1:`RVLEN0] data_rs1_reg;
    reg [`RVLENM1:`RVLEN0] data_rs2_reg;
//----------------------------------------------------------------------//
//=============================== WIRES ================================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//=========================== STATE MACHINE ============================//
//----------------------------------------------------------------------//
  
//----------------------------------------------------------------------//
//=========================== INSTANTIATIONS ===========================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//============================== PROCESS ===============================//
//----------------------------------------------------------------------//
    always @(posedge clk_i or posedge rst_i) begin
        if(rst_i) begin
            data_rs1_reg <= `A0;
            data_rs2_reg <= `A0;
            memRS1[0]  <= `RV32B0;
            memRS1[1]  <= `RV32B0;
            memRS1[2]  <= `RV32B0;
            memRS1[3]  <= `RV32B0;
            memRS1[4]  <= `RV32B0;
            memRS1[5]  <= `RV32B0;
            memRS1[6]  <= `RV32B0;
            memRS1[7]  <= `RV32B0;
            memRS1[8]  <= `RV32B0;
            memRS1[9]  <= `RV32B0;
            memRS1[10] <= `RV32B0;
            memRS1[11] <= `RV32B0;
            memRS1[12] <= `RV32B0;
            memRS1[13] <= `RV32B0;
            memRS1[14] <= `RV32B0;
            memRS1[15] <= `RV32B0;
            memRS1[16] <= `RV32B0;
            memRS1[17] <= `RV32B0;
            memRS1[18] <= `RV32B0;
            memRS1[19] <= `RV32B0;
            memRS1[20] <= `RV32B0;
            memRS1[21] <= `RV32B0;
            memRS1[22] <= `RV32B0;
            memRS1[23] <= `RV32B0;
            memRS1[24] <= `RV32B0;
            memRS1[25] <= `RV32B0;
            memRS1[26] <= `RV32B0;
            memRS1[27] <= `RV32B0;
            memRS1[28] <= `RV32B0;
            memRS1[29] <= `RV32B0;
            memRS1[30] <= `RV32B0;
            memRS1[31] <= `RV32B0;
            memRS2[0]  <= `RV32B0;
            memRS2[1]  <= `RV32B0;
            memRS2[2]  <= `RV32B0;
            memRS2[3]  <= `RV32B0;
            memRS2[4]  <= `RV32B0;
            memRS2[5]  <= `RV32B0;
            memRS2[6]  <= `RV32B0;
            memRS2[7]  <= `RV32B0;
            memRS2[8]  <= `RV32B0;
            memRS2[9]  <= `RV32B0;
            memRS2[10] <= `RV32B0;
            memRS2[11] <= `RV32B0;
            memRS2[12] <= `RV32B0;
            memRS2[13] <= `RV32B0;
            memRS2[14] <= `RV32B0;
            memRS2[15] <= `RV32B0;
            memRS2[16] <= `RV32B0;
            memRS2[17] <= `RV32B0;
            memRS2[18] <= `RV32B0;
            memRS2[19] <= `RV32B0;
            memRS2[20] <= `RV32B0;
            memRS2[21] <= `RV32B0;
            memRS2[22] <= `RV32B0;
            memRS2[23] <= `RV32B0;
            memRS2[24] <= `RV32B0;
            memRS2[25] <= `RV32B0;
            memRS2[26] <= `RV32B0;
            memRS2[27] <= `RV32B0;
            memRS2[28] <= `RV32B0;
            memRS2[29] <= `RV32B0;
            memRS2[30] <= `RV32B0;
            memRS2[31] <= `RV32B0;
        end else begin
            if(en_i) begin
                data_rs1_reg <= memRS1[sel_rs1_i];
                data_rs2_reg <= memRS2[sel_rs2_i];
                if(we_i) begin
                    memRS1[sel_rd_i] <= data_i;
                    memRS2[sel_rd_i] <= data_i;
                end
            end
        end
    end
//----------------------------------------------------------------------//
//============================== ASSIGNS ===============================//
//----------------------------------------------------------------------//
    assign data_rs1_o = (sel_rs1_i != `RV5B0) ? data_rs1_reg : `RV32B0;
    assign data_rs2_o = (sel_rs2_i != `RV5B0) ? data_rs2_reg : `RV32B0;

endmodule
