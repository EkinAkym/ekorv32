`include "ekorv32_defines.vh"

//----------------------------------------------------------------------//
//================ MODULE PARAMETERS,INPUTS AND OUTPUTS ================//
//----------------------------------------------------------------------//
module ekorv32_memory (
    input clk_i,
    input rst_i,
    input mem_en_i,
    input mem_we_i,
    input [`A11:`A0] mem_addr_i,
    input [`RVLENM1:`RVLEN0] mem_data_i,
    output [`RVLENM1:`RVLEN0] mem_data_o,
    output mem_ready_o,
    output mem_data_ready_o
);
//----------------------------------------------------------------------//
//============================ LOCALPARAMS =============================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//============================= REGISTERS ==============================//
//----------------------------------------------------------------------//
    (* ram_style = "block" *) reg [`RVLENM1:`RVLEN0] MEM_ARR [`RVLEN0:`MEM_DEPTHM1];
    reg [`RVLENM1:`RVLEN0] mem_data_reg;
    reg mem_data_ready_reg;
    reg mem_ready_reg;
//----------------------------------------------------------------------//
//=============================== WIRES ================================//
//----------------------------------------------------------------------//
//----------------------------------------------------------------------//
//=========================== STATE MACHINE ============================//
//----------------------------------------------------------------------//
//----------------------------------------------------------------------//
//=========================== INSTANTIATIONS ===========================//
//----------------------------------------------------------------------//

//----------------------------------------------------------------------//
//============================== PROCESS ===============================//
//----------------------------------------------------------------------//
initial begin
    MEM_ARR[0]  = 32'h00000097;
    MEM_ARR[1]  = 32'h02008093;
    MEM_ARR[2]  = 32'h00001137;
    MEM_ARR[3]  = 32'h00200413;
    MEM_ARR[4]  = 32'h02814133;
    MEM_ARR[5]  = 32'h00a00193;
    MEM_ARR[6]  = 32'h01400213;
    MEM_ARR[7]  = 32'h004182b3;
    MEM_ARR[8]  = 32'h40320333;
    MEM_ARR[9]  = 32'h00512023;
    MEM_ARR[10] = 32'h00012383;
end
always @(posedge clk_i) begin
    if (rst_i) begin
        mem_data_reg <= `A0;
        mem_ready_reg <= `RV1B0;
        mem_data_ready_reg <= `RV1B0;
    end else begin
        mem_ready_reg <= `RV1B1;
        if (mem_en_i) begin
            if (mem_we_i) begin
                MEM_ARR[mem_addr_i] <= mem_data_i;
                mem_data_ready_reg <= `RV1B0;
            end else begin
                mem_data_reg <= MEM_ARR[mem_addr_i];
                mem_data_ready_reg <= `RV1B1;
            end
        end else begin
            mem_data_ready_reg <= `RV1B0;
        end
    end
end
//----------------------------------------------------------------------//
//============================== ASSIGNS ===============================//
//----------------------------------------------------------------------//
    assign mem_data_o = mem_data_reg;
    assign mem_ready_o = mem_ready_reg;
    assign mem_data_ready_o = mem_data_ready_reg;
endmodule
